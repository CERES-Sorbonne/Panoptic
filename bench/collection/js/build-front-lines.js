'use strict'
// Builds js/dist/front-lines.js: the REAL scroller layout modules of the front, type-stripped with
// the front's own TypeScript and wrapped into one plain script (a `FrontLines` global), so lines.js
// runs them unchanged under node and the jsc shell. They only have type imports, so no bundler is
// needed; the build fails if a runtime import ever appears.
//   node js/build-front-lines.js
const fs = require('fs'), path = require('path')
const FRONT = path.resolve(__dirname, '../../../panoptic_front')
const ts = require(FRONT + '/node_modules/typescript')
const MODULES = {
    scrollLayout: 'src/components/scrollers/virtual/scrollLayout.ts',
    treeLines: 'src/components/scrollers/tree/treeLines.ts',
    gridLines: 'src/components/scrollers/grid/gridLines.ts',
    sha1Piles: 'src/core/sha1Piles.ts',
}
let out = '// Generated by build-front-lines.js from panoptic_front sources. Do not edit.\nvar FrontLines = (function () {\nconst M = {}\n'
for (const [name, rel] of Object.entries(MODULES)) {
    const src = fs.readFileSync(path.join(FRONT, rel), 'utf8')
    const js = ts.transpileModule(src, {
        fileName: rel,
        compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, importsNotUsedAsValues: 'remove', verbatimModuleSyntax: false },
    }).outputText
    if (/\brequire\(/.test(js)) throw new Error(`${rel} has a runtime import: bundle it instead`)
    out += `// ── ${rel}\nM.${name} = (function () { const exports = {};\n${js}\nreturn exports })()\n`
}
out += 'return M\n})()\nif (typeof module !== "undefined") module.exports = FrontLines\n'
fs.mkdirSync(path.join(__dirname, 'dist'), { recursive: true })
fs.writeFileSync(path.join(__dirname, 'dist/front-lines.js'), out)
console.error('wrote js/dist/front-lines.js')
